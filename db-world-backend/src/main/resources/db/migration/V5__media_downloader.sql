CREATE TABLE IF NOT EXISTS media_download_job (
    id VARCHAR(255) NOT NULL PRIMARY KEY,
    owner VARCHAR(255) NOT NULL,
    url VARCHAR(4096) NOT NULL,
    title VARCHAR(1000),
    thumbnail VARCHAR(4096),
    preset VARCHAR(255),
    quality VARCHAR(255),
    status VARCHAR(255),
    file_name VARCHAR(255),
    bytes_downloaded BIGINT NOT NULL DEFAULT 0,
    bytes_total BIGINT NOT NULL DEFAULT 0,
    speed DOUBLE NOT NULL DEFAULT 0,
    eta BIGINT,
    progress DOUBLE,
    error VARCHAR(1500),
    created_at DATETIME(6),
    completed_at DATETIME(6),
    expires_at DATETIME(6),
    subtitles BIT NOT NULL DEFAULT 0,
    thumbnail_file BIT NOT NULL DEFAULT 0,
    subtitle_language VARCHAR(255),
    audio_language VARCHAR(255),
    start_seconds DOUBLE,
    end_seconds DOUBLE,
    INDEX idx_download_owner_created (owner, created_at),
    INDEX idx_download_expiry (expires_at)
);